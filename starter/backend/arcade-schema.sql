-- Migration for A Little Intermission: shared views + server-validated arcade scores.
-- Run in Supabase Dashboard -> SQL Editor for project ymauqmpqersjfmovlvvk.
-- Score inserts are only performed by the arcade-api Edge Function using its server-side secret key.

create table if not exists public.arcade_scores (
  id bigint generated by default as identity primary key,
  game_id text not null check (game_id in ('snake', 'tetris', 'breakout', 'pacman')),
  player_name text not null check (
    char_length(btrim(player_name)) between 2 and 18
    and player_name = btrim(player_name)
  ),
  score integer not null check (score between 1 and 100000),
  created_at timestamptz not null default now()
);

-- Preserve scores for retired games as historical data. The Edge Function no longer accepts
-- those game IDs, and the UI no longer shows their leaderboards.
-- Reconcile the game ID constraints on both fresh and previously created tables.
alter table public.arcade_scores drop constraint if exists arcade_scores_game_id_check;
alter table public.arcade_scores add constraint arcade_scores_game_id_check
  check (game_id in ('snake', 'tetris', 'breakout', 'pacman'));

create index if not exists arcade_scores_leaderboard_idx
  on public.arcade_scores (game_id, score desc, created_at asc);

alter table public.arcade_scores enable row level security;

-- Remove the previous direct-anonymous-write policies/grants from the casual prototype.
drop policy if exists "Anyone can read arcade scores" on public.arcade_scores;
drop policy if exists "Visitors can submit basic arcade scores" on public.arcade_scores;
revoke all on table public.arcade_scores from anon, authenticated;
revoke all on sequence public.arcade_scores_id_seq from anon, authenticated;
grant all on table public.arcade_scores to service_role;
grant usage, select on sequence public.arcade_scores_id_seq to service_role;

create table if not exists public.arcade_runs (
  id uuid primary key default gen_random_uuid(),
  game_id text not null check (game_id in ('snake', 'tetris', 'breakout', 'pacman')),
  seed bigint not null,
  ip_hash text not null,
  created_at timestamptz not null default now(),
  used_at timestamptz
);

delete from public.arcade_runs where game_id not in ('snake', 'tetris', 'breakout', 'pacman');
alter table public.arcade_runs drop constraint if exists arcade_runs_game_id_check;
alter table public.arcade_runs add constraint arcade_runs_game_id_check
  check (game_id in ('snake', 'tetris', 'breakout', 'pacman'));

create index if not exists arcade_runs_rate_idx
  on public.arcade_runs (ip_hash, created_at desc);

alter table public.arcade_runs enable row level security;
revoke all on table public.arcade_runs from anon, authenticated;
grant all on table public.arcade_runs to service_role;

create table if not exists public.site_page_views (
  id bigint generated by default as identity primary key,
  page_id text not null check (page_id in ('home', 'arcade')),
  visitor_hash text not null,
  ip_hash text not null,
  visit_day date not null default current_date,
  created_at timestamptz not null default now(),
  unique (page_id, visitor_hash, visit_day)
);

create index if not exists site_page_views_page_idx
  on public.site_page_views (page_id, created_at desc);
create index if not exists site_page_views_ip_idx
  on public.site_page_views (ip_hash, created_at desc);

alter table public.site_page_views enable row level security;
revoke all on table public.site_page_views from anon, authenticated;
revoke all on sequence public.site_page_views_id_seq from anon, authenticated;
grant all on table public.site_page_views to service_role;
grant usage, select on sequence public.site_page_views_id_seq to service_role;

